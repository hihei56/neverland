'use strict';

// プライバシーポリシー。内容を変えたら PRIVACY_POLICY_VERSION を更新すること
// （同意記録・同意ログには同意時の版が残る）。

function privacyPolicy({ app, retentionDays, publicBaseUrl }) {
    return {
        title: `${app.name} プライバシーポリシー`,
        sections: [
            ['版', app.policyVersion],
            ['運営者', `${app.operatorName}（連絡先: ${app.contact}）`],
            ['1. 利用目的', `${app.purpose}\nこの目的以外には使用しません。第三者への提供・販売・広告目的での利用は行いません。`],
            ['2. 取得する情報', [
                'Discord の公式 OAuth2 認可画面で、あなたが許可した場合だけ次の情報を取得します。',
                '・ユーザーID、ユーザー名、表示名（identify）',
                '・メールアドレスとその確認状態（email）',
                '・Discord に連携している外部アカウントの種類・ID・名前・確認状態・公開設定（connections）',
                '・同意日時、同意したポリシーの版、許可されたスコープ',
                'メッセージ、参加サーバー、フレンド、DM、IP アドレスは取得・保存しません。',
                '同意しなかった場合や認可をキャンセルした場合、情報は一切取得・保存しません。',
            ].join('\n')],
            ['3. 取得方法', 'あなた自身の OAuth2 アクセストークンでだけ取得します。Bot などを使って他の方法で情報を集めることはしません。'],
            ['4. 保管', [
                'メールアドレス・連携アカウント情報・アクセストークンは AES-256-GCM で暗号化して保存します。',
                'アプリのログにはメールアドレスやトークンを記録しません。',
                `保存期間は同意から ${retentionDays} 日です。期間を過ぎると自動で削除し、トークンも失効させます。`,
            ].join('\n')],
            ['5. 同意の撤回（オプトアウト）', [
                `${publicBaseUrl}/me で本人確認をすると、いつでも撤回できます。`,
                '撤回すると、トークンを Discord 側で失効させて破棄し、メールアドレスと連携アカウント情報を消去します。撤回の記録として、ユーザーIDと撤回日時だけを残します。',
                'Discord の「設定 > 認証済みアプリ」から連携を解除した場合も、次に確認した時点で撤回として扱います。',
            ].join('\n')],
            ['6. 削除', [
                'ユーザーIDを含むすべての記録の削除は、運営者が行います。上記の連絡先までご依頼ください。本人確認のうえ、速やかに削除します。',
                'なお、5. の同意の撤回だけでも、メールアドレス・連携アカウント情報・トークンはあなた自身の操作ですぐに消去できます。',
                '同意・撤回・削除の証跡として、ユーザーIDを復元できない形に変換した ID（仮名ID）と日時・種別だけを記録した同意ログが残ります。このログの削除も希望する場合は、連絡先までご連絡ください。',
            ].join('\n')],
            ['7. 開示', `${publicBaseUrl}/me で、保存されているあなたのデータをすべて確認できます。`],
            ['8. 変更', 'このポリシーを変更した場合は版を更新します。利用目的を変える場合は、改めて同意をいただきます。'],
        ],
    };
}

module.exports = { privacyPolicy };
